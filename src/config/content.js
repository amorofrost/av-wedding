const LOCAL_PATH = path.join(path.dirname(fileURLToPath(import.meta.url)), 'content.local.js');

// ── Загрузка личных данных ───────────────────────────────────────────────────
// Файла нет — не стартуем вовсе. Иначе сайт молча поднялся бы с заглушками
// («Имя невесты & Имя жениха»), и заметили бы это уже гости.
//
// Наличие проверяем именно на диске, а не по ошибке импорта: ERR_MODULE_NOT_FOUND
// прилетает и когда сам content.local.js импортирует что-то несуществующее, и по
// тексту ошибки эти случаи не различить. Всё, что бросит импорт существующего
// файла (синтаксис, битый импорт внутри), пробрасываем как есть.
if (!fs.existsSync(LOCAL_PATH)) {
  console.error('✗ Нет файла src/config/content.local.js — в нём личные данные свадьбы.');
  console.error('  Скопируйте шаблон и впишите свои значения:');
  console.error('    cp src/config/content.example.js src/config/content.local.js');
  process.exit(1);
}

const overrides = (await import('./content.local.js')).default;

if (!overrides || typeof overrides !== 'object' || Array.isArray(overrides)) {
  console.error('✗ src/config/content.local.js должен экспортировать объект: export default { ... }');
  process.exit(1);
}

// Слияние на один уровень: объекты дополняются по ключам (можно переопределить
// только couple.bride, не повторяя hashtag и фото), массивы и простые значения
// заменяются целиком — иначе пришлось бы решать, как «дополнить» расписание.
function isPlainObject(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

function merge(base, patch) {
  const out = { ...base };
  for (const [key, value] of Object.entries(patch)) {
    out[key] =
      isPlainObject(base[key]) && isPlainObject(value) ? { ...base[key], ...value } : value;
  }
  return out;
}

export const content = merge(defaults, overrides);

export default content;
