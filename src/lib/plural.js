// ─────────────────────────────────────────────────────────────────────────────
// Выбор формы существительного по числу.
//
// Нужен ровно в одном месте — в подтверждении RSVP («2 гостя»), но правило
// достаточно неочевидное, чтобы держать его отдельно и покрыть тестами.
// ─────────────────────────────────────────────────────────────────────────────

// Русский и украинский используют одно и то же правило трёх форм.
function slavicForm(n) {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return 'one';
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return 'few';
  return 'many';
}

// forms: { one, few, many } для ru/uk и { one, other } для en.
// Если нужной формы нет — откатываемся на one, а затем на пустую строку,
// чтобы шаблон не падал на неполном словаре.
export function plural(lang, n, forms = {}) {
  const count = Math.abs(Number(n));
  const key = Number.isNaN(count)
    ? 'many'
    : lang === 'en'
      ? count === 1
        ? 'one'
        : 'other'
      : slavicForm(count);

  return forms[key] ?? forms.one ?? '';
}
